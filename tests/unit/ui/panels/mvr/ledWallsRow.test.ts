// @vitest-environment jsdom
/** The "LED walls" row of the import summary: starts at 25 %, offers off to 100 %, reports each choice, shows its notes. */
import { expect, it } from 'vitest';
import { ledWallsRow } from '../../../../../src/ui/panels/mvr/ledWallsRow.ts';

it('starts at 25 %, reports each change in per cent and shows the notes', () => {
  const host = document.body.appendChild(document.createElement('div'));
  const levels: number[] = [];
  const notes = ['LED content is generated by the desk; it is not in the file', '3 duplicate panels are hidden'];
  const looks: string[] = [];
  const control = {
    set: (percent: number) => levels.push(percent),
    looks: ['fields', 'bars'],
    notes,
    level: 25,
    look: 'fields',
  };
  const select = ledWallsRow(host, { ...control, setLook: (look) => looks.push(look) });
  expect(select.value).toBe('25');
  // a summary that opens later starts at the level and look the walls have then
  const later = ledWallsRow(document.createElement('div'), {
    ...control,
    setLook: () => undefined,
    level: 50,
    look: 'bars',
  });
  expect([later.value, later.closest('div')?.querySelector<HTMLSelectElement>('#mvrLedLook')?.value]).toEqual([
    '50',
    'bars',
  ]);
  expect(Array.from(select.options).map((option) => option.textContent)).toEqual([
    'off',
    '10 %',
    '25 %',
    '50 %',
    '100 %',
  ]);
  for (const value of ['0', '100']) {
    select.value = value;
    select.dispatchEvent(new Event('change'));
  }
  expect(levels).toEqual([0, 100]);
  expect(host.textContent).toContain('LED walls');
  // B.O. is a lighting blackout; the row says that the walls stay on
  expect(select.closest('label')?.title).toMatch(/B\.O\. is a lighting blackout.*stay on/);
  const look = host.querySelector<HTMLSelectElement>('#mvrLedLook');
  expect(Array.from(look?.options ?? []).map((option) => option.textContent)).toEqual(['Colour fields', 'Light bars']);
  if (look) look.value = 'bars';
  look?.dispatchEvent(new Event('change'));
  expect(looks).toEqual(['bars']);
  expect(Array.from(host.querySelectorAll('.mvrLedNote')).map((line) => line.textContent)).toEqual(notes);
});
