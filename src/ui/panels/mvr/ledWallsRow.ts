import { createElement } from '../../shared';

/** The wall levels on offer, per cent; 0 is "off", which leaves the black mask of the tiles. */
export const LED_WALL_LEVELS = [0, 10, 25, 50, 100] as const;

/** What the LED rows need: how to set level and look, the looks on offer, and what the desk did, in plain lines. */
export interface LedWallsControl {
  /** The level and the look the walls have now; the rows start there. */
  readonly level: number;
  readonly look: string;
  readonly set: (percent: number) => void;
  readonly looks: readonly string[];
  readonly setLook: (look: string) => void;
  readonly notes: readonly string[];
}

/** The desk's blackout does not reach the walls; the row says so where the user sets them. */
const LEVEL_TIP =
  'Level of the LED walls. B.O. is a lighting blackout: LED walls are video, they stay on, and only this row sets them.';
/**
 * The one sentence that says whose the wall content is. It stands as a note in the layer list and in the tooltips of
 * the "LED" box and of the top bar's LED level, so generated content is never taken for file data.
 */
export const LED_GENERATED = 'LED content is generated by the desk; it is not in the file';
const LOOK_TIP = `Content the desk generates for LED walls. ${LED_GENERATED}.`;

/** Moves the level row of an open layer list to `percent`, after the top bar set it; nothing without the row. */
export function syncLedRow(percent: number): void {
  const select = typeof document === 'undefined' ? null : document.getElementById('mvrLedWalls');
  if (select && 'value' in select) select.value = String(percent);
}
const LOOK_NAMES: Readonly<Record<string, string>> = { fields: 'Colour fields', bars: 'Light bars', bokeh: 'Bokeh' };

/** One labelled select in the layer list; `options` are value and text. */
function selectRow(host: HTMLElement, label: string, tip: string, options: readonly (readonly [string, string])[]) {
  const row = createElement('label', 'mvrLayer');
  row.title = tip;
  const name = createElement('span');
  name.textContent = label;
  const select = createElement('select');
  for (const [value, text] of options) {
    const option = createElement('option');
    option.value = value;
    option.textContent = text;
    select.appendChild(option);
  }
  row.appendChild(name);
  row.appendChild(select);
  host.appendChild(row);
  return select;
}

/**
 * The LED rows of the import summary: the level of every LED wall of the stage, the generated content look, then
 * the notes, which say what on the walls is the desk's and not the file's. They stand beside the controls, where they
 * are always in view. The labels are English inline, like the other summary labels.
 */
export function ledWallsRow(host: HTMLElement, control: LedWallsControl): HTMLSelectElement {
  const levels = LED_WALL_LEVELS.map((percent) => [String(percent), percent === 0 ? 'off' : `${percent} %`] as const);
  const level = selectRow(host, 'LED walls', LEVEL_TIP, levels);
  level.id = 'mvrLedWalls';
  level.value = String(control.level);
  level.onchange = () => control.set(Number(level.value));
  const look = selectRow(
    host,
    'LED content',
    LOOK_TIP,
    control.looks.map((id) => [id, LOOK_NAMES[id] ?? id] as const),
  );
  look.id = 'mvrLedLook';
  look.value = control.look;
  look.onchange = () => control.setLook(look.value);
  for (const note of control.notes) {
    const line = createElement('div', 'mvrLedNote');
    line.textContent = note;
    host.appendChild(line);
  }
  return level;
}
